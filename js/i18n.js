/**
 * Thay thế tham số dạng {key} trong chuỗi I18N.
 */
export function formatText(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) =>
    params[key] !== undefined ? String(params[key]) : `{${key}}`
  );
}
