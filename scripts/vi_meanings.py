def fill_unit_by_unit() -> None:
    """Populate meaning_vi in data/vocab.json unit by unit and run validate_data.py after each unit."""
    vocab = json.loads(VOCAB_PATH.read_text(encoding="utf-8"))
    missing_ids = [r["id"] for r in vocab if r["id"] not in MEANINGS_VI]
    if missing_ids:
        raise RuntimeError(f"Missing MEANINGS_VI entries for: {missing_ids}")

    groups: dict[tuple[str, str, int], list[dict]] = defaultdict(list)
    for rec in vocab:
        groups[(rec["source"], rec["level"], int(rec["unit"]))].append(rec)

    sorted_keys = sorted(groups.keys())
    for idx, key in enumerate(sorted_keys, 1):
        source, level, unit = key
        for rec in groups[key]:
            rec["meaning_vi"] = MEANINGS_VI[rec["id"]]

        VOCAB_PATH.write_text(
            json.dumps(vocab, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        res = subprocess.run(
            [sys.executable, str(VALIDATE_SCRIPT)],
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        summary_line = res.stdout.strip().splitlines()[0] if res.stdout.strip() else ""
        print(
            f"[{idx}/{len(sorted_keys)}] Filled {source} {level} U{unit} "
            f"({len(groups[key])} words) -> validate exit={res.returncode}: {summary_line}"
        )
        if idx == len(sorted_keys) and res.returncode != 0:
            print(res.stdout)
            print(res.stderr)
            sys.exit(res.returncode)


if __name__ == "__main__":
    fill_unit_by_unit()
